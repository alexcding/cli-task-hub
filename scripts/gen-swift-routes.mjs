import { ROUTES } from '../src/shared/routes.mjs';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../macos/Services/Backend/Routes.swift', import.meta.url));
const quote = value => JSON.stringify(value);
const entries = Object.entries(ROUTES).map(([key, value]) => {
  if (typeof value === 'string') return `    public static let ${key} = ${quote(value)}`;
  if (typeof value !== 'function' || value.length !== 1) throw new Error(`Unsupported route: ${key}`);
  const marker = 'TASKHUB_ROUTE_PARAMETER';
  const path = value(marker);
  if (!path.includes(marker)) throw new Error(`Missing parameter: ${key}`);
  // Preserve the JS builder's encoding behavior (some IDs are inserted verbatim).
  const encoded = value('a/b') !== path.replace(marker, 'a/b');
  const interpolation = encoded ? '\\(encodeComponent(value))' : '\\(value)';
  return `    public static func ${key}(_ value: String) -> String {\n        ${quote(path).replace(marker, interpolation)}\n    }`;
});
const output = `// Generated by scripts/gen-swift-routes.mjs. Do not edit.\nimport Foundation\n\npublic enum Routes {\n${entries.join('\n')}\n\n    private static func encodeComponent(_ value: String) -> String {\n        let allowed = CharacterSet(charactersIn: "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_.!~*'()")\n        return value.addingPercentEncoding(withAllowedCharacters: allowed)!\n    }\n}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Swift routes are stale; run node scripts/gen-swift-routes.mjs');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
}
